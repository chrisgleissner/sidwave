/**
 * Generates doc/opcodes.md from the opcode inventory (src/opcodeInventory.ts).
 *
 *   node scripts/gen-opcode-table.mjs          write doc/opcodes.md
 *   node scripts/gen-opcode-table.mjs --check  exit 1 when doc/opcodes.md differs from the generated text
 *
 * test/opcodeTable.test.mjs fails when the committed page differs from renderOpcodesPage().
 * Node 24 runs this file directly: it imports the TypeScript inventory, which uses only erasable syntax.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { OPCODE_INVENTORY, opcodeSize } from "../src/opcodeInventory.ts";

const MODE_NAMES = {
  implied: "implied",
  accumulator: "accumulator",
  immediate: "immediate",
  zeroPage: "zero page",
  zeroPageX: "zero page,X",
  zeroPageY: "zero page,Y",
  zeroPageS: "stack relative",
  relative: "relative",
  absolute: "absolute",
  absoluteX: "absolute,X",
  absoluteY: "absolute,Y",
  indirect: "indirect",
  indirectX: "(zero page,X)",
  indirectY: "(zero page),Y",
};

const OPERAND = {
  implied: "",
  accumulator: " A",
  immediate: " #$nn",
  zeroPage: " $nn",
  zeroPageX: " $nn,X",
  zeroPageY: " $nn,Y",
  zeroPageS: " $nn,S",
  relative: " $aaaa",
  absolute: " $aaaa",
  absoluteX: " $aaaa,X",
  absoluteY: " $aaaa,Y",
  indirect: " ($aaaa)",
  indirectX: " ($nn,X)",
  indirectY: " ($nn),Y",
};

const hex2 = (value) => `$${value.toString(16).toUpperCase().padStart(2, "0")}`;

/**
 * The opcode the assembler emits for a mnemonic and mode: the lowest documented opcode when there is one,
 * otherwise the lowest opcode (the rule of buildInstructionTable in src/assembler.ts).
 */
function assembledOpcode(entry) {
  const same = OPCODE_INVENTORY.filter((other) => other.mnemonic === entry.mnemonic && other.mode === entry.mode);
  return (same.find((other) => !other.illegal) ?? same[0]).opcode;
}

export function renderOpcodesPage(inventory = OPCODE_INVENTORY) {
  const documented = inventory.filter((entry) => !entry.illegal).length;
  const rows = inventory.map((entry) => {
    const assembled = assembledOpcode(entry);
    const note = assembled === entry.opcode ? "" : `same as ${hex2(assembled)}; the assembler emits ${hex2(assembled)}`;
    const jam = entry.mnemonic === "JAM" ? "stops the CPU until reset" : "";
    return `| ${hex2(entry.opcode)} | ${entry.mnemonic} | ${MODE_NAMES[entry.mode]} | \`${entry.mnemonic}${OPERAND[entry.mode]}\` | ${opcodeSize(entry.mode)} | ${entry.illegal ? "undocumented" : "documented"} | ${[note, jam].filter(Boolean).join("; ")} |`;
  });
  return [
    "# Opcode table",
    "",
    "<!-- Generated by scripts/gen-opcode-table.mjs from src/opcodeInventory.ts. Do not edit by hand. -->",
    "",
    `All 256 opcode bytes of the NMOS 6502 and 6510. ${documented} are documented and ${inventory.length - documented} are undocumented.`,
    "The assembler and the disassembler use the same inventory (`OPCODE_INVENTORY`, see [api.md](api.md)).",
    "",
    "Names follow the 1541 Ultimate monitor: `JAM` (also written HLT or KIL), `SLO` (ASO), `SRE` (LSE), `DCP` (DCM) and `ISC` (INS).",
    "The assembler accepts only these canonical names.",
    "",
    "Several undocumented opcodes have the same mnemonic and addressing mode as another opcode. The assembler emits the lowest documented opcode for such a pair, or the lowest opcode when none is documented.",
    "The disassembler decodes every opcode byte. Assembling the disassembled text of an alias therefore gives the other opcode of the pair: same length, same operand, same effect on the CPU.",
    "",
    "In the Syntax column, `nn` is a byte, `aaaa` is an address. For a branch, `aaaa` is the target address; the assembler computes the offset.",
    "",
    "| Opcode | Mnemonic | Mode | Syntax | Bytes | Status | Note |",
    "| --- | --- | --- | --- | --- | --- | --- |",
    ...rows,
    "",
  ].join("\n");
}

export const OPCODES_PAGE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "doc", "opcodes.md");

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = renderOpcodesPage();
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(OPCODES_PAGE) ? fs.readFileSync(OPCODES_PAGE, "utf8") : "";
    if (current !== text) {
      console.error("doc/opcodes.md is out of date; run: node scripts/gen-opcode-table.mjs");
      process.exitCode = 1;
    }
  } else {
    fs.writeFileSync(OPCODES_PAGE, text);
    console.log(`wrote ${path.relative(process.cwd(), OPCODES_PAGE)}`);
  }
}
